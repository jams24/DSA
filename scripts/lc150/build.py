"""Build the LeetCode 150 study guide.

Every reference solution is executed against its tests before src/content/leetcode150-guide.ts is
written, so the site never ships a solution that doesn't run.

    python3 scripts/lc150/build.py
"""

import json
import pathlib
import re
import sys
import traceback

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

import g1, g2, g3, g4, g5  # noqa: E402

GUIDES = {}
PATTERNS = {}
for mod in (g1, g2, g3, g4, g5):
    GUIDES.update(mod.GUIDES)
    PATTERNS.update(mod.PATTERNS)

PRELUDE = '''
from typing import List, Optional, Dict, Tuple
import collections, heapq, math, bisect, random, functools, itertools
from collections import defaultdict, deque, Counter, OrderedDict
from functools import lru_cache, cache

class ListNode:
    def __init__(self, val=0, next=None):
        self.val = val
        self.next = next

class TreeNode:
    def __init__(self, val=0, left=None, right=None):
        self.val = val
        self.left = left
        self.right = right

def L(xs):
    dummy = ListNode()
    cur = dummy
    for x in xs:
        cur.next = ListNode(x)
        cur = cur.next
    return dummy.next

def tolist(node):
    out = []
    while node:
        out.append(node.val)
        node = node.next
    return out

def T(xs):
    """Build a tree from LeetCode's level-order list (None = missing child)."""
    if not xs or xs[0] is None:
        return None
    nodes = [None if x is None else TreeNode(x) for x in xs]
    kids = iter(nodes[1:])
    for node in nodes:
        if node is None:
            continue
        node.left = next(kids, None)
        node.right = next(kids, None)
    return nodes[0]

def levels(root):
    """Level-order values without trailing Nones (LeetCode's serialization)."""
    out, q = [], deque([root])
    while q:
        node = q.popleft()
        out.append(None if node is None else node.val)
        if node:
            q.append(node.left)
            q.append(node.right)
    while out and out[-1] is None:
        out.pop()
    return out

def find(root, val):
    if root is None or root.val == val:
        return root
    return find(root.left, val) or find(root.right, val)
'''


def main():
    src = (ROOT / "src/content/leetcode150.ts").read_text()
    slugs = re.findall(r'"slug": "([^"]+)"', src)
    categories = re.findall(r'"category": "([^"]+)"', src)
    errors = []
    missing = [s for s in slugs if s not in GUIDES]
    extra = [s for s in GUIDES if s not in slugs]
    if missing:
        errors.append(f"missing guides: {missing}")
    if extra:
        errors.append(f"guides for unknown slugs: {extra}")
    for c in categories:
        if c not in PATTERNS:
            errors.append(f"missing pattern guide: {c}")

    tested = 0
    for slug in slugs:
        g = GUIDES.get(slug)
        if not g:
            continue
        for field in ("trick", "steps", "time", "space", "pitfall", "code"):
            if not g[field]:
                errors.append(f"{slug}: empty {field}")
        ns = {}
        try:
            exec(PRELUDE, ns)
            exec(compile(g["code"], f"<{slug}>", "exec"), ns)
            if g["test"]:
                exec(compile(g["test"], f"<{slug} test>", "exec"), ns)
                tested += 1
        except Exception:
            errors.append(f"{slug}: {traceback.format_exc(limit=2).strip().splitlines()[-1]}")
    for name, p in PATTERNS.items():
        try:
            compile(p["template"], f"<template {name}>", "exec")
        except SyntaxError as e:
            errors.append(f"template {name}: {e}")

    if errors:
        print("\n".join(errors))
        sys.exit(1)

    guides = {s: {k: v for k, v in GUIDES[s].items() if k != "test"} for s in slugs}
    out = ROOT / "src/content/leetcode150-guide.ts"
    out.write_text(
        "// Generated by scripts/lc150/build.py: edit the Python sources there, then re-run it.\n"
        "// Every solution below passed its tests at build time.\n\n"
        "export interface LcGuide {\n  trick: string;\n  steps: string[];\n  time: string;\n  space: string;\n  pitfall: string;\n  code: string;\n}\n\n"
        "export interface LcPattern {\n  recognize: string[];\n  tips: string[];\n  template: string;\n}\n\n"
        f"export const LC_GUIDE: Record<string, LcGuide> = {json.dumps(guides, indent=2, ensure_ascii=False)};\n\n"
        f"export const LC_PATTERNS: Record<string, LcPattern> = {json.dumps({c: PATTERNS[c] for c in dict.fromkeys(categories)}, indent=2, ensure_ascii=False)};\n"
    )
    print(f"✓ {len(guides)} guides ({tested} solutions tested), {len(set(categories))} pattern guides → {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
