// Embeds the challenge-code/ sources referenced by the challenges into a TS module the pages import.
// Run with: npm run challenges:gen   (npm run validate fails if the output is stale)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CHALLENGES } from "../src/content/challenges";

export const OUT = join(__dirname, "../src/content/challenges/code.generated.ts");

export function renderChallengeCode(): string {
  const files = [...new Set(CHALLENGES.flatMap((c) => c.solutions.flatMap((s) => [s.file, ...(s.test ? [s.test] : [])])))].sort();
  const code = Object.fromEntries(files.map((f) => [f, readFileSync(join(__dirname, "../challenge-code", f), "utf8")]));
  return `// Generated by scripts/gen-challenge-code.ts from challenge-code/. Do not edit by hand.\n\nexport const CODE: Record<string, string> = ${JSON.stringify(code, null, 2)};\n`;
}

if (require.main === module) {
  writeFileSync(OUT, renderChallengeCode());
  console.log(`wrote ${OUT}`);
}
